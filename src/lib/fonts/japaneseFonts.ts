export const japaneseFontOptions = japaneseFonts.map(({ family }) => ({ value: family, label: family }));

/** 許可されたフォント名かを確認する。 */
export function isJapaneseFont(value: string): boolean {
  return japaneseFonts.some((font) => font.family === value);
}

/** CSS属性にはカタログ掲載名だけを使用する。 */
export function fontFamilyStyle(value: string): string {
  return value === "inherit" ? "inherit" : `'${isJapaneseFont(value) ? value : "Noto Sans JP"}', sans-serif`;
}
